"""
Unit Test Suite: Splink 5.0 Fellegi-Sunter Probabilistic Linker & Entity Clustering
==================================================================================
Verifies mathematical record linkage, DuckDB registration, Expectation-Maximization
parameter estimation, Jaro-Winkler string distance scoring, and statutory conflict guards.
"""

import sys
import unittest
from pathlib import Path

# Add project root to sys.path
_PROJECT_ROOT = Path(__file__).resolve().parents[3]
if str(_PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(_PROJECT_ROOT))

from packages.domain.splink_engine import SplinkIdentityLinker


class TestSplinkEngine(unittest.TestCase):
    """Test suite for Splink 5.0 probabilistic entity resolution on DuckDB."""

    def setUp(self):
        self.linker = SplinkIdentityLinker(probability_two_random_records_match=0.01)

    def test_auto_merge_identical_domain_and_name(self):
        """Pairs with identical domain and high name similarity must auto-merge (P >= 0.95)."""
        records = [
            {
                "id": "org-001",
                "name": "Acme Cloud Solutions Inc.",
                "domain": "acmecloud.io",
                "state": "CA",
                "postal_code": "94105",
                "ein": "12-3456789",
            },
            {
                "id": "org-002",
                "name": "Acme Cloud Solutions LLC",
                "domain": "acmecloud.io",
                "state": "CA",
                "postal_code": "94105",
                "ein": "12-3456789",
            },
        ]
        results = self.linker.link_records(records, threshold_match_probability=0.70)
        self.assertGreater(len(results), 0, "Expected at least 1 match pair generated by Splink")
        match = results[0]
        self.assertIn(match["decision"], ("AUTO_MERGE", "QUARANTINE_REVIEW"))
        self.assertGreaterEqual(match["match_probability"], 0.85)
        self.assertTrue(match["match_features"]["domain_match"])

    def test_statutory_id_conflict_rejection(self):
        """Even with identical names and states, conflicting valid EINs must NEVER merge."""
        records = [
            {
                "id": "org-101",
                "name": "Starlight Capital Corp",
                "domain": "starlight.com",
                "state": "NY",
                "postal_code": "10001",
                "ein": "11-1111111",
            },
            {
                "id": "org-102",
                "name": "Starlight Capital Corp",
                "domain": "starlight.com",
                "state": "NY",
                "postal_code": "10001",
                "ein": "22-2222222",  # Explicitly conflicting EIN
            },
        ]
        results = self.linker.link_records(records, threshold_match_probability=0.50)
        self.assertEqual(len(results), 0, "Match must be rejected due to statutory tax ID conflict")

    def test_distinct_entities_not_matched(self):
        """Entities in different states with different names and domains must not produce links."""
        records = [
            {
                "id": "org-201",
                "name": "Apollo Global Management",
                "domain": "apollo.com",
                "state": "NY",
                "postal_code": "10019",
            },
            {
                "id": "org-202",
                "name": "Zebra Technologies",
                "domain": "zebra.com",
                "state": "IL",
                "postal_code": "60069",
            },
        ]
        results = self.linker.link_records(records, threshold_match_probability=0.70)
        self.assertEqual(len(results), 0, "Distinct entities must not produce matches")

    def test_quarantine_heuristic_adjudication(self):
        """QUARANTINE_REVIEW decisions can be adjudicated synchronously."""
        sample_results = [
            {
                "source_id": "org-301",
                "target_id": "org-302",
                "match_probability": 0.82,
                "match_weight": 4.5,
                "decision": "QUARANTINE_REVIEW",
            }
        ]
        lookup = {
            "org-301": {"name": "Apex Logistics", "domain": "apexlogistics.com", "state": "TX"},
            "org-302": {"name": "Apex Logistics Services", "domain": "apexlogistics.com", "state": "TX"},
        }
        adjudicated = self.linker.adjudicate_quarantine_sync(sample_results, lookup)
        self.assertEqual(len(adjudicated), 1)
        self.assertIn("adjudication", adjudicated[0])
        self.assertIn(adjudicated[0]["decision"], ("AUTO_MERGE_LLM", "DISTINCT_LLM", "QUARANTINE_REVIEW"))


if __name__ == "__main__":
    unittest.main()

